        return shortSurahs.find { it.surahNumber == surahNumber }
    }

    fun searchAmalContent(query: String): List<IslamicTopicItem> {
        if (query.isBlank()) return importantDuas23 + additionalAmals26
        val q = query.trim().lowercase()
        val all = importantDuas23 + additionalAmals26
        return all.filter {
            it.titleBengali.lowercase().contains(q) ||
            it.translationBengali.lowercase().contains(q) ||
            it.transliteration.lowercase().contains(q) ||
            it.explanation.lowercase().contains(q) ||
            it.reference.lowercase().contains(q)
        }
    }
