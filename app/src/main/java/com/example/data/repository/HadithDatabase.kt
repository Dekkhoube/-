    /**
     * Search Hadith intelligently:
     * - If query contains a number (Bengali or English), prioritizes exact hadithNumber match!
     * - Searches text in Bengali, Arabic, Narrator, Chapter, Reference & Explanation.
     */
    fun searchHadith(query: String, selectedCollectionId: String = "all"): List<Hadith> {
        val baseList = if (selectedCollectionId == "all") {
            allHadiths
        } else {
            allHadiths.filter { it.collectionId == selectedCollectionId }
        }

        if (query.isBlank()) return baseList

        val trimmed = query.trim()
        val searchedNumber = extractHadithNumber(trimmed)
        val normalizedQuery = normalizeToEnglishDigits(trimmed).lowercase()

        // Partition results: Exact number matches first, then keyword matches
        val exactNumberMatches = if (searchedNumber != null) {
            baseList.filter { it.hadithNumber == searchedNumber }
        } else emptyList()

        val textMatches = baseList.filter { hadith ->
            if (searchedNumber != null && hadith.hadithNumber == searchedNumber) {
                false // already in exactNumberMatches
            } else {
                hadith.textBengali.lowercase().contains(trimmed.lowercase()) ||
                hadith.textArabic.contains(trimmed) ||
                hadith.chapterBengali.lowercase().contains(trimmed.lowercase()) ||
                hadith.narratorBengali.lowercase().contains(trimmed.lowercase()) ||
                hadith.reference.lowercase().contains(trimmed.lowercase()) ||
                hadith.explanationBengali.lowercase().contains(trimmed.lowercase()) ||
                hadith.transliteration.lowercase().contains(trimmed.lowercase()) ||
                normalizeToEnglishDigits(hadith.reference).contains(normalizedQuery)
            }
        }

        return exactNumberMatches + textMatches
    }

    /**
     * Direct Hadith Number Lookup
     */
    fun getHadithByNumber(collectionId: String, hadithNumber: Int): Hadith? {
        return allHadiths.find {
            (collectionId == "all" || it.collectionId == collectionId) && it.hadithNumber == hadithNumber
        }
    }

    /**
     * Real-time online lookup via Gemini / Firebase AI Logic for ANY Hadith Number (1 to 7563).
     * If a user queries e.g. Sahih Bukhari #2500 or Muslim #1200 that is not yet bundled offline,
     * this fetches the authentic Arabic text, Bengali translation, narrator, and explanation!
     */
    suspend fun fetchHadithFromOnlineLibrary(collectionName: String, hadithNumber: Int): Hadith? {
        return try {
            val model = Firebase.ai.generativeModel(modelName = "gemini-3.8-flash")
            val prompt = """
                Provide the exact authentic Hadith number $hadithNumber from $collectionName.
                Respond in valid JSON format only, matching this structure:
                {
                  "collectionId": "bukhari",
                  "bookNumber": 1,
                  "hadithNumber": $hadithNumber,
                  "chapterBengali": "অধ্যায় নাম",
                  "narratorBengali": "বর্ণনাকারীর নাম (রা.)",
                  "textArabic": "الأحاديث باللغة العربية مع التشكيل",
                  "transliteration": "বাংলা উচ্চারণ",
                  "textBengali": "সহীহ ও বিশুদ্ধ বাংলা অনুবাদ",
                  "grade": "সহীহ",
                  "reference": "$collectionName: হাদিস $hadithNumber",
                  "explanationBengali": "হাদিসের শিক্ষণীয় বিষয় ও সংক্ষিপ্ত ব্যাখ্যা"
                }
            """.trimIndent()

            val response = withTimeout(20_000L) {
                model.generateContent(prompt)
            }

            val text = response.text?.trim() ?: return null
            // Strip code fences if present
            val cleanedJson = text.removePrefix("```json").removePrefix("```").removeSuffix("```").trim()
            val obj = JSONObject(cleanedJson)

            Hadith(
                id = 90000 + hadithNumber,
                collectionId = obj.optString("collectionId", "bukhari"),
                bookNumber = obj.optInt("bookNumber", 1),
                hadithNumber = obj.optInt("hadithNumber", hadithNumber),
                chapterBengali = obj.optString("chapterBengali", "হাদিস $hadithNumber"),
                narratorBengali = obj.optString("narratorBengali", "সাহাবী (রা.)"),
                textArabic = obj.optString("textArabic", ""),
                transliteration = obj.optString("transliteration", ""),
                textBengali = obj.optString("textBengali", ""),
                grade = obj.optString("grade", "সহীহ"),
                reference = obj.optString("reference", "$collectionName: $hadithNumber"),
                explanationBengali = obj.optString("explanationBengali", "")
            )
        } catch (e: Exception) {
            Log.e(TAG, "Error fetching hadith online: ${e.message}", e)
            null
        }
    }
